export const CHAR_W = 4; // 3px glyph + 1px spacing
export const CHAR_H = 6;

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
): void {
  ctx.fillStyle = color;
  let cx = x;
  for (const raw of text.toUpperCase()) {
    const glyph = GLYPHS[raw] ?? GLYPHS['?']!;
    for (let gy = 0; gy < 5; gy++) {
      const row = glyph[gy]!;
      for (let gx = 0; gx < 3; gx++) {
        if (row[gx] === '1') ctx.fillRect(cx + gx * scale, y + gy * scale, scale, scale);
      }
    }
    cx += CHAR_W * scale;
  }
}

export function textWidth(text: string, scale = 1): number {
  return text.length * CHAR_W * scale - scale;
}

export function drawTextCentered(
  ctx: CanvasRenderingContext2D,
  text: string,
  cx: number,
  y: number,
  color: string,
  scale = 1,
): void {
  drawText(ctx, text, Math.round(cx - textWidth(text, scale) / 2), y, color, scale);
}
