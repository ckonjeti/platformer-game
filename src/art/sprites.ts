export function buildSpikeSprites(pal: ChapterPalette): Record<'up' | 'down' | 'left' | 'right', HTMLCanvasElement> {
  const p: Palette = [pal.spike, pal.terrainDark];
  const up = [
    '........',
    '........',
    '........',
    '...0....',
    '...00.0.',
    '.0.00.0.',
    '.0000000',
    '00000000',
  ];
  const upC = spriteFromStrings(p, up);
  const downC = (() => {
    const c = document.createElement('canvas');
    c.width = 8;
    c.height = 8;
    const ctx = c.getContext('2d')!;
    ctx.translate(0, 8);
    ctx.scale(1, -1);
    ctx.drawImage(upC, 0, 0);
    return c;
  })();
  const rot = (deg: number) => {
    const c = document.createElement('canvas');
    c.width = 8;
    c.height = 8;
    const ctx = c.getContext('2d')!;
    ctx.translate(4, 4);
    ctx.rotate((deg * Math.PI) / 180);
    ctx.drawImage(upC, -4, -4);
    return c;
  };
  return { up: upC, down: downC, left: rot(-90), right: rot(90) };
}
