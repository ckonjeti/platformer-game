export interface PlayerAnims {
  idle: Anim;
  run: Anim;
  jump: Anim;
  fall: Anim;
  dash: Anim;
  climb: Anim;
}

export interface DirectionalAnims {
  right: PlayerAnims;
  left: PlayerAnims;
}

function makeAnim(palette: Palette, frames: string[][], rate: number, loop = true): { right: Anim; left: Anim } {
  const right = frames.map((f) => spriteFromStrings(palette, f));
  const left = right.map(flipX);
  return {
    right: { frames: right, rate, loop },
    left: { frames: left, rate, loop },
  };
}

export function buildPlayerSprites(pal: ChapterPalette): DirectionalAnims {
  const p: Palette = [pal.player.outline, pal.player.cloak, pal.player.shade, pal.player.face, pal.player.light];
  const sets = pal.hooded
    ? {
        idle: [HOODED_IDLE_1, HOODED_IDLE_2],
        run: [HOODED_RUN_1, HOODED_RUN_2, HOODED_RUN_3, HOODED_RUN_4],
        jump: [HOODED_JUMP],
        fall: [HOODED_FALL],
        dash: [HOODED_DASH],
        climb: [HOODED_CLIMB_1, HOODED_CLIMB_2],
      }
    : {
        idle: [FREE_IDLE_1, FREE_IDLE_2],
        run: [FREE_RUN_1, FREE_RUN_2, FREE_RUN_3, FREE_RUN_4],
        jump: [FREE_JUMP],
        fall: [FREE_FALL],
        dash: [FREE_DASH],
        climb: [FREE_CLIMB_1, FREE_CLIMB_2],
      };
  const idle = makeAnim(p, sets.idle, 32);
  const run = makeAnim(p, sets.run, 7);
  const jump = makeAnim(p, sets.jump, 10);
  const fall = makeAnim(p, sets.fall, 10);
  const dash = makeAnim(p, sets.dash, 10);
  const climb = makeAnim(p, sets.climb, 14);
  return {
    right: { idle: idle.right, run: run.right, jump: jump.right, fall: fall.right, dash: dash.right, climb: climb.right },
    left: { idle: idle.left, run: run.left, jump: jump.left, fall: fall.left, dash: dash.left, climb: climb.left },
  };
}

